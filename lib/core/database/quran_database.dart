import 'dart:async';
import 'package:path/path.dart';
import 'package:sqflite/sqflite.dart';
import 'package:flutter/services.dart' show rootBundle;
import 'dart:io';

class QuranDatabase {
  static const String dbName = 'quran_comprehensive.db';
  static const int dbVersion = 1;
  static Database? _database;

  Future<Database> get database async {
    if (_database != null) return _database!;
    _database = await _initDb();
    return _database!;
  }

  Future<Database> _initDb() async {
    final dbPath = await getDatabasesPath();
    final path = join(dbPath, dbName);

    // Check if the pre-populated database exists in the app's documents directory.
    // If not, copy it from assets (generated by the Python pipeline in Phase 3).
    if (!await File(path).exists()) {
      await _copyDbFromAssets(path);
    }

    return await openDatabase(
      path,
      version: dbVersion,
      onConfigure: (db) async {
        // Enforce foreign key constraints
        await db.execute('PRAGMA foreign_keys = ON');
      },
      onUpgrade: _onUpgrade,
    );
  }

  Future<void> _copyDbFromAssets(String path) async {
    try {
      final ByteData data = await rootBundle.load('assets/databases/quran.db');
      final List<int> bytes = data.buffer.asUint8List(data.offsetInBytes, data.lengthInBytes);
      await File(path).writeAsBytes(bytes, flush: true);
    } catch (e) {
      throw Exception('Failed to copy database from assets. Ensure the Python pipeline was executed.');
    }
  }

  Future<void> _onUpgrade(Database db, int oldVersion, int newVersion) async {
    // Migration logic will be implemented here for future schema changes
  }
}